function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <SiteShell><Outlet /></SiteShell> breaks all child routes. */}
      <SiteShell>
        <Outlet />
      </SiteShell>
    </QueryClientProvider>
  );
}
